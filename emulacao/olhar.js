// Um olhar na emulação: largura de computador e de celular, com um fluxo de reparo.
const { chromium } = require('playwright');
const [arquivo, dir] = process.argv.slice(2);
(async () => {
  const b = await chromium.launch({ args: ['--no-sandbox'] });
  const erros = [];
  for (const [nome, vp] of [['pc', { width: 1280, height: 820 }], ['celular', { width: 390, height: 800 }]]) {
    const ctx = await b.newContext({ viewport: vp, deviceScaleFactor: nome === 'pc' ? 1 : 2, hasTouch: nome !== 'pc' });
    const p = await ctx.newPage();
    p.on('console', m => { if (m.type() === 'error') erros.push(nome + ' console: ' + m.text()); });
    p.on('pageerror', e => erros.push(nome + ' erro: ' + e.message));
    await p.goto('file://' + arquivo);
    await p.waitForTimeout(700);
    await p.screenshot({ path: `${dir}/${nome}-0-inicio.png` });
    await p.waitForSelector('#app:not([hidden])', { timeout: 15000 });
    await p.waitForTimeout(1200);
    await p.screenshot({ path: `${dir}/${nome}-1-sistemas.png` });
    const larg = await p.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
    if (larg > 0) erros.push(nome + ': rolagem horizontal de ' + larg + 'px');
    const cartao = n => p.locator('.cartao', { has: p.locator('h2', { hasText: new RegExp('^' + n) }) }).first();
    await cartao('SIGADAER').locator('button', { hasText: 'Reparar' }).click();
    await p.waitForSelector('#folha .folha-lista');
    await p.waitForTimeout(400);
    await p.screenshot({ path: `${dir}/${nome}-2-confirmar.png` });
    await p.locator('#folha button', { hasText: 'Continuar' }).click();
    await p.waitForSelector('#folha button:has-text("Fechar")', { timeout: 30000 });
    await p.locator('#folha button', { hasText: 'Fechar' }).click();
    await p.waitForTimeout(2200);
    const selo = (await cartao('SIGADAER').locator('.selo').first().innerText()).trim();
    if (selo !== 'Pronto') erros.push(nome + ': SIGADAER ficou ' + selo);
    await p.click('#nav [data-pagina="tokens"]'); await p.waitForTimeout(500);
    await p.screenshot({ path: `${dir}/${nome}-3-tokens.png` });
    await cartao('DXToken').locator('button', { hasText: 'Instalar' }).click();
    await p.locator('#folha button', { hasText: 'Continuar' }).click();
    await p.waitForSelector('#folha button:has-text("Fechar")', { timeout: 30000 });
    await p.locator('#folha button', { hasText: 'Fechar' }).click();
    await p.waitForTimeout(2200);
    await cartao('DXToken').locator('button', { hasText: 'Ajustar' }).click();
    await p.waitForTimeout(2500);
    const feito = await cartao('DXToken').locator('.linha', { hasText: 'Ajuste para o Método Alfa' }).innerText();
    if (!/Feito/.test(feito)) erros.push(nome + ': ajuste não apareceu como feito: ' + feito);
    await p.click('#nav [data-pagina="acesso"]'); await p.waitForTimeout(500);
    await p.screenshot({ path: `${dir}/${nome}-6-acesso.png` });
    await cartao('Instalar sem administrador').locator('button', { hasText: 'Liberar este computador' }).click();
    await p.locator('#folha button', { hasText: /^Liberar$/ }).click();
    await p.waitForSelector('#folha button:has-text("Fechar")', { timeout: 30000 });
    await p.locator('#folha button', { hasText: 'Fechar' }).click();
    await p.waitForTimeout(2400);
    const lib = (await cartao('Instalar sem administrador').locator('.selo').first().innerText()).trim();
    if (lib !== 'Liberado') erros.push(nome + ': acesso ficou ' + lib);
    await p.screenshot({ path: `${dir}/${nome}-7-acesso-liberado.png` });
    await p.click('#nav [data-pagina="tutoriais"]'); await p.waitForTimeout(500);
    await p.screenshot({ path: `${dir}/${nome}-4-tutoriais.png` });
    await p.click('#nav [data-pagina="diagnostico"]'); await p.waitForTimeout(700);
    await p.screenshot({ path: `${dir}/${nome}-5-diagnostico.png` });
    const larg2 = await p.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
    if (larg2 > 0) erros.push(nome + ': rolagem horizontal de ' + larg2 + 'px no diagnóstico');
    await ctx.close();
  }
  console.log('ERROS', erros.length); erros.forEach(e => console.log('  ' + e));
  await b.close();
})();
